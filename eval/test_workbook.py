"""A requirements workbook that is also a test: every row has an Expected rung.

Attach it in the app; each sheet becomes a routine and every built row is run against its
Expected rung in the scan simulator (equivalent rungs count as right). Sheets:

  Series, Parallel, Nested, Multi_output  generated by eval/suite.py (realistic tag names)
  Referenced                              chains where later rows use what earlier rows made
                                          (a timer's .DN, a latched alarm, a counter, a total)
  Real_world                              rungs from real exports, with their plain-English
                                          read-back as the requirement (needs --corpus)

Every expected answer is checked before it is written: the LogicSpec that says the same thing
is compiled and must behave like the Expected rung, so the sheet holds no impossible rows.

    python -m eval.test_workbook out.xlsx [--seed 3] [--rows 12] [--corpus folder_of_L5X]
"""

from __future__ import annotations

import argparse
import random
import re
from pathlib import Path

from core.catalog import default_catalog
from core.compiler import Compiler
from core.logicspec import format_spec, parse_spec
from core.rung import Branch, Instr, Rung, Series, format_rung, parse_rung, walk
from eval.rung_compare import Side, _refs, compare
from eval.suite import make_case

TIMED = {"TON", "TOF", "RTO", "CTU", "CTD"}

# (requirement, expected rung, the same in LogicSpec) — each chain builds on its own earlier rows
REFERENCED = [
    ("Run Pump_Run: start it with Start_PB and keep it running until Stop_PB is pressed or Pump_Fault is on.",
     "[XIC(Start_PB) ,XIC(Pump_Run) ]XIO(Stop_PB)XIO(Pump_Fault)OTE(Pump_Run);",
     "Pump_Run := (Start_PB OR Pump_Run) AND NOT Stop_PB AND NOT Pump_Fault;"),
    ("While Pump_Run is on, run the on-delay timer Pump_Run_TMR with a 5 second preset.",
     "XIC(Pump_Run)TON(Pump_Run_TMR,5000,0);",
     "IF Pump_Run THEN ON_DELAY_TIMER(Pump_Run_TMR, 5s);"),
    ("When Pump_Run_TMR is done and Pressure_OK is off, latch No_Pressure_Alarm.",
     "XIC(Pump_Run_TMR.DN)XIO(Pressure_OK)OTL(No_Pressure_Alarm);",
     "IF Pump_Run_TMR.DN AND NOT Pressure_OK THEN SET No_Pressure_Alarm;"),
    ("Unlatch No_Pressure_Alarm when Reset_PB is pressed and Pump_Run is off.",
     "XIC(Reset_PB)XIO(Pump_Run)OTU(No_Pressure_Alarm);",
     "IF Reset_PB AND NOT Pump_Run THEN RESET No_Pressure_Alarm;"),
    ("Turn on Alarm_Horn while No_Pressure_Alarm is on and Horn_Silence is off.",
     "XIC(No_Pressure_Alarm)XIO(Horn_Silence)OTE(Alarm_Horn);",
     "Alarm_Horn := No_Pressure_Alarm AND NOT Horn_Silence;"),
    ("Count each box on Box_Eye with the up counter Box_CTR; the batch is done at 12 boxes.",
     "XIC(Box_Eye)CTU(Box_CTR,12,0);",
     "IF Box_Eye THEN COUNT_UP(Box_CTR, 12);"),
    ("Turn on Batch_Done while Box_CTR is done.",
     "XIC(Box_CTR.DN)OTE(Batch_Done);",
     "Batch_Done := Box_CTR.DN;"),
    ("Reset Box_CTR when Batch_Reset_PB is pressed or Line_Auto is off.",
     "[XIC(Batch_Reset_PB) ,XIO(Line_Auto) ]RES(Box_CTR);",
     "IF Batch_Reset_PB OR NOT Line_Auto THEN RESET_ACC Box_CTR;"),
    ("Run Conveyor_Run while Line_Auto is on and Batch_Done is off.",
     "XIC(Line_Auto)XIO(Batch_Done)OTE(Conveyor_Run);",
     "Conveyor_Run := Line_Auto AND NOT Batch_Done;"),
    ("Add Flow_A and Flow_B and store the result in Total_Flow.",
     "ADD(Flow_A,Flow_B,Total_Flow);",
     "IF TRUE THEN Total_Flow := Flow_A + Flow_B;"),
    ("Turn on High_Flow_Alarm when Total_Flow is greater than 500.",
     "GRT(Total_Flow,500)OTE(High_Flow_Alarm);",
     "High_Flow_Alarm := Total_Flow > 500;"),
    ("When High_Flow_Alarm is on, set Flow_Setpoint to 0 and latch Flow_Tripped.",
     "XIC(High_Flow_Alarm)[MOV(0,Flow_Setpoint) ,OTL(Flow_Tripped) ];",
     "IF High_Flow_Alarm THEN Flow_Setpoint := 0, SET Flow_Tripped;"),
]


def with_presets(rung: Rung, presets: dict[str, int]) -> Rung:
    """TON(T,?,?) -> TON(T,5000,0) so the Expected cell carries the preset."""
    def fix(e):
        if isinstance(e, Branch):
            return Branch(tuple(Series(tuple(fix(x) for x in leg.items)) for leg in e.legs))
        if e.name.upper() in TIMED and e.args and e.args[0] in presets and len(e.args) == 3:
            return Instr(e.name, (e.args[0], str(presets[e.args[0]]), "0"))
        return e
    return Rung(Series(tuple(fix(x) for x in rung.body.items)), rung.comment)


def presets_of(rungs) -> dict[str, int]:
    return {i.args[0]: int(float(i.args[1])) for r in rungs for i in walk(r.body)
            if i.name.upper() in TIMED and len(i.args) > 1 and re.fullmatch(r"-?\d+(\.\d+)?", i.args[1])}


def behaves_like(spec: str, expected: list[Rung], known: dict[str, str] | None = None) -> tuple[bool, str]:
    res = Compiler(known_tags=known).compile(parse_spec(spec))
    got_presets = {t.name: t.preset for t in res.tags.values() if t.preset}
    return compare(Side(expected, presets_of(expected)), Side(res.rungs, {**presets_of(expected), **got_presets}))


def buildable(spec: str) -> bool:
    """Would the app accept this answer with no project attached (tags made from use only)?"""
    from core.validator import errors, validate
    res = Compiler().compile(parse_spec(spec))
    return not errors(validate(res.rungs, {t.name: t.datatype for t in res.tags.values()}))


def suite_sheet(rng: random.Random, structure: str, want: int) -> list[tuple]:
    """Rows of one structure, every instruction family represented, no tag written by two rows."""
    from eval.suite import INSTRUCTIONS
    rows, written, n = [], set(), 0
    feats = INSTRUCTIONS[:]
    rng.shuffle(feats)
    cat = default_catalog()
    while len(rows) < want and n < 400:
        feat = feats[n % len(feats)]
        n += 1
        case = make_case(rng, feat, structure, n, 35)
        if any("COP(" in t for t in case.rungs):  # COP needs array tags from a project; a sheet has none
            continue
        main = [parse_rung(t) for t in case.rungs if t not in case.context]
        ctx = [parse_rung(t) for t in case.context]
        writes = {w.split(".")[0].split("[")[0] for w in _refs(Side(ctx + main, {}), cat)[2]}
        if writes & written:
            continue
        written |= writes
        for c, spec in zip(ctx, case.context_spec):  # an earlier row the case refers to
            rows.append(("", "", format_rung(with_presets(c, case.presets)), "context: written as rung text", spec))
        rows.append((case.english, "", "\n".join(format_rung(with_presets(r, case.presets)) for r in main),
                     f"{case.feature}", case.answer))
    return rows


def real_world_sheet(folder: Path, rng: random.Random, want: int) -> list[tuple]:
    from explain.decompiler import try_decompile
    from explain.describe import describe_statement
    from l5x.reader import read_l5x
    plain = re.compile(r"^[A-Za-z_]\w*(\.(DN|EN|TT|ACC|PRE))?$")
    pool = []
    for f in sorted(p for p in folder.rglob("*") if p.suffix.lower() == ".l5x"):
        p = read_l5x(f.read_bytes())
        pre = p.presets()
        for rt in p.routines:
            for x in rt.rungs:
                if x.rung is None:
                    continue
                ins = list(walk(x.rung.body))
                complex_ = any(isinstance(e, Branch) for e in x.rung.body.items) or len(ins) >= 4
                if not complex_ or any(not plain.match(a) and not re.fullmatch(r"-?[\d.]+|\?", a)
                                       for i in ins for a in i.args):
                    continue
                stmts, _ = try_decompile(x.rung, pre)
                if stmts:
                    pool.append((f.name, x.rung, stmts, pre))
    rng.shuffle(pool)
    rows, seen = [], set()
    for name, rung, stmts, pre in pool:
        exp = with_presets(Rung(rung.body), pre)
        key = format_rung(exp)
        if key in seen:
            continue
        spec = format_spec(stmts)
        ok, _ = behaves_like(spec, [exp])
        if not ok or not buildable(spec):  # e.g. T.DN of a timer the sheet never creates
            continue
        seen.add(key)
        rows.append((" ".join(describe_statement(s) for s in stmts), "", key, f"from {name}", spec))
        if len(rows) >= want:
            break
    return rows


def build(out: Path, seed: int = 3, rows: int = 12, corpus: Path | None = None) -> dict[str, int]:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    rng = random.Random(seed)
    sheets = {s.title(): suite_sheet(rng, s, rows) for s in ("series", "parallel", "nested")}
    sheets["Multi_output"] = suite_sheet(rng, "multi_output", rows)
    sheets["Referenced"] = [(r, "", e, "uses earlier rows of this sheet", s) for r, e, s in REFERENCED]
    if corpus:
        sheets["Real_world"] = real_world_sheet(corpus, rng, rows)
    # every expected answer must be reachable: its LogicSpec compiles to the same behaviour
    for title, rs in sheets.items():
        for req, logic, exp, _, spec in rs:
            ok, why = behaves_like(spec, [parse_rung(t) for t in exp.splitlines()])
            if not ok:
                raise SystemExit(f"{title}: expected answer not reachable ({why}): {req or logic} -> {exp}")
    wb = Workbook()
    wb.remove(wb.active)
    for title, rs in sheets.items():
        ws = wb.create_sheet(title)
        ws.append(["Rung", "Requirement", "Rung text", "Expected rung", "Note"])
        for c in ws[1]:
            c.font = Font(bold=True, color="FFFFFF")
            c.fill = PatternFill("solid", fgColor="16233A")
        for n, (req, _, exp, note, _) in enumerate(rs, 1):
            # context rows have no requirement: their rung text is passed through as written
            ws.append([n, req, "" if req else exp, exp, note])
        for col, w in zip("ABCDE", (6, 80, 34, 60, 30)):
            ws.column_dimensions[col].width = w
        for r in ws.iter_rows(min_row=2):
            for c in r:
                c.alignment = Alignment(wrap_text=True, vertical="top")
        ws.freeze_panes = "A2"
    info = wb.create_sheet("How to use")
    for line in [
        f"LLM4L5X test workbook, seed {seed}. Attach it in the app: each sheet becomes a routine, rows are built one by one.",
        "Expected rung: what the row must behave like. Rows are run against it in the scan simulator, so an equivalent",
        "rung written differently counts as right. The score per routine is in the summary and in Report.txt.",
        "Rows with Rung text and no Requirement are context (an earlier rung the next row refers to); the model is not asked.",
        "Referenced: later rows use timers, latches, counters and totals made by earlier rows, by name.",
        "Real_world: rungs from public exports; the requirement is LLM4L5X's own read-back of the rung, so that sheet",
        "favours this tool's wording. Treat its score as an upper bound.",
    ]:
        info.append([line])
    info.column_dimensions["A"].width = 120
    wb.save(out)
    return {k: len(v) for k, v in sheets.items()}


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("out", type=Path)
    ap.add_argument("--seed", type=int, default=3)
    ap.add_argument("--rows", type=int, default=12)
    ap.add_argument("--corpus", type=Path)
    a = ap.parse_args()
    print(build(a.out, a.seed, a.rows, a.corpus))
