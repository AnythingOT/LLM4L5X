def with_presets(rung: Rung, presets: dict[str, int]) -> Rung:
    """TON(T,?,?) -> TON(T,5000,0) so the Expected cell carries the preset."""
    def fix(e):
        if isinstance(e, Branch):
            return Branch(tuple(Series(tuple(fix(x) for x in leg.items)) for leg in e.legs))
        if e.name.upper() in TIMED and e.args and e.args[0] in presets and len(e.args) == 3:
            return Instr(e.name, (e.args[0], str(presets[e.args[0]]), "0"))
        return e
    return Rung(Series(tuple(fix(x) for x in rung.body.items)), rung.comment)


def presets_of(rungs) -> dict[str, int]:
    return {i.args[0]: int(float(i.args[1])) for r in rungs for i in walk(r.body)
            if i.name.upper() in TIMED and len(i.args) > 1 and re.fullmatch(r"-?\d+(\.\d+)?", i.args[1])}


def behaves_like(spec: str, expected: list[Rung], known: dict[str, str] | None = None) -> tuple[bool, str]:
    res = Compiler(known_tags=known).compile(parse_spec(spec))
    got_presets = {t.name: t.preset for t in res.tags.values() if t.preset}
    return compare(Side(expected, presets_of(expected)), Side(res.rungs, {**presets_of(expected), **got_presets}))


def buildable(spec: str) -> bool:
    """Would the app accept this answer with no project attached (tags made from use only)?"""
    from core.validator import errors, validate
    res = Compiler().compile(parse_spec(spec))
    return not errors(validate(res.rungs, {t.name: t.datatype for t in res.tags.values()}))


def _writes(rungs) -> set[str]:
    return {w.split(".")[0].split("[")[0] for w in _refs(Side(list(rungs), {}), default_catalog())[2]}


def suite_sheet(rng: random.Random, structure: str, want: int, written: set[str] | None = None,
                level: int = 1) -> list[tuple]:
    """Rows of one structure, every instruction family represented, no tag written by two rows.

    `written` is shared by the whole workbook: every sheet goes into one program, so a timer
    run on two sheets would be one timer with two owners (and two presets)."""
    from eval.suite import INSTRUCTIONS
    rows, n = [], 0
    written = set() if written is None else written
    feats = INSTRUCTIONS[:]
    rng.shuffle(feats)
    while len(rows) < want and n < 5000:
        feat = feats[n % len(feats)]
        n += 1
        case = make_case(rng, feat, structure, n, 35, level)
        if any("COP(" in t for t in case.rungs):  # COP needs array tags from a project; a sheet has none
            continue
        main = [parse_rung(t) for t in case.rungs if t not in case.context]
        ctx = [parse_rung(t) for t in case.context]
        writes = _writes(ctx + main)
        if writes & written:
            continue
        written |= writes
        for c, spec in zip(ctx, case.context_spec):  # an earlier row the case refers to
            rows.append(("", "", format_rung(with_presets(c, case.presets)), "context: written as rung text", spec))
        rows.append((case.english, "", "\n".join(format_rung(with_presets(r, case.presets)) for r in main),
                     f"{case.feature}", case.answer))
    return rows


# Lint rules that judge one rung on its own: a rung with any of these is test data, not logic to
# copy (the L5Sharp sample [XIC(B),XIC(B)][OTE(B),OTU(B)] checks a parser, and no sentence asks for it).
# Rules that need the rest of the program (a counter reset in another rung) are left out.
_SELF_CONTRADICTORY = {"ERR001", "ERR002", "ERR003", "ERR010", "ERR014"}


def nonsense(rung: Rung, tag_types: dict[str, str] | None = None) -> str | None:
    """Why a public rung is no fair test, or None.

    A rung that reads its own output stays: that is a seal-in, [XIC(Start),XIC(Motor)]XIO(Stop)OTE(Motor)."""
    import lint
    for f in lint.check_rungs([rung], tag_types):
        if f.code in _SELF_CONTRADICTORY:
            return f"{f.code} {f.message}"
    kinds: dict[str, set[str]] = {}
    for i in walk(rung.body):
        if i.name in ("OTE", "OTL", "OTU") and i.args:
            kinds.setdefault(i.args[0], set()).add(i.name)
    both = sorted(t for t, k in kinds.items() if len(k) > 1)
    return f"{both[0]} is turned on and off in the same rung" if both else None


def real_world_sheet(folder: Path, rng: random.Random, want: int, written: set[str] | None = None) -> list[tuple]:
    from explain.decompiler import try_decompile
    from core.describe import describe_statement
    from l5x.reader import read_l5x
    plain = re.compile(r"^[A-Za-z_]\w*(\.(DN|EN|TT|ACC|PRE))?$")
    pool = []
    for f in sorted(p for p in folder.rglob("*") if p.suffix.lower() == ".l5x"):
        p = read_l5x(f.read_bytes())
        pre = p.presets()
        for rt in p.routines:
            for x in rt.rungs:
                if x.rung is None:
                    continue
                ins = list(walk(x.rung.body))
                complex_ = any(isinstance(e, Branch) for e in x.rung.body.items) or len(ins) >= 4
                if not complex_ or any(not plain.match(a) and not re.fullmatch(r"-?[\d.]+|\?", a)
                                       for i in ins for a in i.args):
                    continue
                if nonsense(x.rung, p.tag_types()):
                    continue
                stmts, _ = try_decompile(x.rung, pre)
                if stmts:
                    pool.append((f.name, x.rung, stmts, pre))
    rng.shuffle(pool)
    rows, seen = [], set()
    written = set() if written is None else written
    for name, rung, stmts, pre in pool:
        exp = with_presets(Rung(rung.body), pre)
        key = format_rung(exp)
        if key in seen or _writes([exp]) & written:
            continue
        spec = format_spec(stmts)
        try:
            ok = behaves_like(spec, [exp])[0] and buildable(spec)
        except SpecError:  # CompileError too: RES of a timer its own project times elsewhere: not reachable here
            ok = False
        if not ok:  # e.g. T.DN of a timer the sheet never creates
            continue
        seen.add(key)
        written |= _writes([exp])
        rows.append((" ".join(describe_statement(s) for s in stmts), "", key, f"from {name}", spec))
        if len(rows) >= want:
            break
    return rows


def build(out: Path, seed: int = 3, rows: int = 12, corpus: Path | None = None, level: int = 1) -> dict[str, int]:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    if corpus is not None:
        if not corpus.is_dir():
            raise SystemExit(f"--corpus {corpus}: no such folder")
        if not any(f.suffix.lower() == ".l5x" for f in corpus.rglob("*")):
            raise SystemExit(f"--corpus {corpus}: no .L5X files in it")
    rng = random.Random(seed)
    # one program: each tag is written by one row of the whole workbook (Referenced's names are fixed, so first)
    written = _writes(parse_rung(e) for _, e, _ in REFERENCED)
    sheets = {s.title(): suite_sheet(rng, s, rows, written, level) for s in ("series", "parallel", "nested")}
    sheets["Multi_output"] = suite_sheet(rng, "multi_output", rows, written, level)
    sheets["Referenced"] = [(r, "", e, "uses earlier rows of this sheet", s) for r, e, s in REFERENCED]
    if corpus:
        sheets["Real_world"] = real_world_sheet(corpus, rng, rows, written)
    # every expected answer must be reachable: its LogicSpec compiles to the same behaviour
    for title, rs in sheets.items():
        for req, logic, exp, _, spec in rs:
            ok, why = behaves_like(spec, [parse_rung(t) for t in exp.splitlines()])
            if not ok:
                raise SystemExit(f"{title}: expected answer not reachable ({why}): {req or logic} -> {exp}")
    wb = Workbook()
    wb.remove(wb.active)
    for title, rs in sheets.items():
        ws = wb.create_sheet(title)
        ws.append(["Rung", "Requirement", "Rung text", "Expected rung", "Note"])
        for c in ws[1]:
            c.font = Font(bold=True, color="FFFFFF")
            c.fill = PatternFill("solid", fgColor="16233A")
        for n, (req, _, exp, note, _) in enumerate(rs, 1):
            # context rows have no requirement: their rung text is passed through as written
            ws.append([n, req, "" if req else exp, exp, note])
        for col, w in zip("ABCDE", (6, 80, 34, 60, 30)):
            ws.column_dimensions[col].width = w
        for r in ws.iter_rows(min_row=2):
            for c in r:
                c.alignment = Alignment(wrap_text=True, vertical="top")
        ws.freeze_panes = "A2"
    info = wb.create_sheet("How to use")
    for line in [
        f"LLM4L5X test workbook, seed {seed}, level {level}. Attach it in the app: each sheet becomes a routine, rows are built one by one.",
        "Expected rung: what the row must behave like. Rows are run against it in the scan simulator, so an equivalent",
        "rung written differently counts as right. The score per routine is in the summary and in Report.txt.",
        "Rows with Rung text and no Requirement are context (an earlier rung the next row refers to); the model is not asked.",
        "Referenced: later rows use timers, latches, counters and totals made by earlier rows, by name.",
        "Real_world: rungs from public exports; the requirement is LLM4L5X's own read-back of the rung, so that sheet",
        "favours this tool's wording. Treat its score as an upper bound.",
    ]:
        info.append([line])
    info.column_dimensions["A"].width = 120
    wb.save(out)
    return {k: len(v) for k, v in sheets.items()}


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("out", type=Path)
    ap.add_argument("--seed", type=int, default=3)
    ap.add_argument("--level", type=int, choices=(1, 2), default=1,
                    help="2: longer series, wider branches, two-group nests, 3-4 outputs per rung")
    ap.add_argument("--rows", type=int, default=12)
    ap.add_argument("--corpus", type=Path)
    a = ap.parse_args()
    counts = build(a.out, a.seed, a.rows, a.corpus, a.level)
    print(counts)
    short = {k: v for k, v in counts.items() if v < a.rows and k != "Referenced"}
    if short:  # a short sheet is not the same test as a full one; say so instead of saving it quietly
        print(f"warning: fewer than {a.rows} rows on {', '.join(f'{k} ({v})' for k, v in short.items())}"
              + ("; Real_world needs more complex rungs in --corpus" if "Real_world" in short else ""))
